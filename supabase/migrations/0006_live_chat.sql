-- Layisha: live chat between dispatchers and drivers
--
-- One conversation per driver (dispatch <-> driver). A message can be tied to an
-- order ("LY-00042: use the back gate"). Broadcasts are stored as one message per
-- driver so read ticks work per driver.
--
-- Live updates: when a message is added or read, a trigger sends a tiny "ping"
-- through Supabase Realtime Broadcast to a secret topic for that driver and for
-- the company. The ping carries NO message content: the app then fetches new
-- messages through its normal, permission-checked routes. So even if a topic
-- name leaked, nobody could read messages from it.

alter table companies add column chat_topic text not null default encode(gen_random_bytes(18), 'hex');
alter table drivers add column chat_topic text not null default encode(gen_random_bytes(18), 'hex');

create table chat_messages (
  id uuid primary key,                       -- generated by the sender's device (safe offline resend)
  company_id uuid not null references companies(id) on delete cascade,
  driver_id uuid not null references drivers(id) on delete cascade,   -- the conversation
  order_id uuid references orders(id) on delete set null,
  sender_type text not null check (sender_type in ('dispatcher', 'driver')),
  sender_user_id uuid references auth.users(id) on delete set null,
  body text not null check (char_length(btrim(body)) between 1 and 1000),
  quick_reply text check (quick_reply is null or char_length(quick_reply) <= 40),
  broadcast_id uuid,
  client_sent_at timestamptz,
  created_at timestamptz not null default now(),
  read_by_driver_at timestamptz,
  read_by_dispatch_at timestamptz
);

create index chat_messages_thread_idx on chat_messages(driver_id, created_at desc);
create index chat_messages_company_idx on chat_messages(company_id, created_at desc);
create index chat_messages_unread_dispatch_idx on chat_messages(company_id)
  where sender_type = 'driver' and read_by_dispatch_at is null;

alter table chat_messages enable row level security;

-- Dispatchers (members of a delivery company) can read their company's chats...
create policy "logistics members read chat" on chat_messages
  for select using (is_logistics_member(company_id));

-- ...and send as themselves. Reads are marked through dispatch_chat_mark_read().
create policy "logistics members send chat" on chat_messages
  for insert with check (
    is_logistics_member(company_id)
    and sender_type = 'dispatcher'
    and sender_user_id = auth.uid()
    and read_by_driver_at is null
    and read_by_dispatch_at is null
  );

-- Messages must stay inside one company: driver and order must belong to it.
create or replace function check_chat_same_company()
returns trigger
language plpgsql
as $$
begin
  if not exists (select 1 from drivers where id = new.driver_id and company_id = new.company_id) then
    raise exception 'Driver belongs to a different company';
  end if;
  if new.order_id is not null
     and not exists (select 1 from orders where id = new.order_id and company_id = new.company_id) then
    raise exception 'Order belongs to a different company';
  end if;
  return new;
end;
$$;

create trigger chat_same_company before insert or update on chat_messages
for each row execute function check_chat_same_company();

-- Live "ping" to the driver's and the company's secret topics.
create or replace function chat_ping()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  d_topic text;
  c_topic text;
begin
  select chat_topic into d_topic from drivers where id = new.driver_id;
  select chat_topic into c_topic from companies where id = new.company_id;
  begin
    perform realtime.send(jsonb_build_object('kind', 'chat'), 'chat', 'drv-' || d_topic, false);
    perform realtime.send(jsonb_build_object('kind', 'chat', 'driver_id', new.driver_id), 'chat', 'co-' || c_topic, false);
  exception when others then
    -- Realtime unavailable (e.g. local testing): the message is still saved,
    -- and apps also check for new messages regularly.
    null;
  end;
  return new;
end;
$$;

create trigger chat_messages_ping after insert or update on chat_messages
for each row execute function chat_ping();

