-- Mark a driver's messages as read by dispatch.
create or replace function dispatch_chat_mark_read(p_driver_id uuid)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  cid uuid;
  n integer;
begin
  select company_id into cid from drivers where id = p_driver_id;
  if cid is null or not is_logistics_member(cid) then
    raise exception 'Not allowed';
  end if;
  update chat_messages
  set read_by_dispatch_at = now()
  where driver_id = p_driver_id and sender_type = 'driver' and read_by_dispatch_at is null;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- Send one message to every active driver.
create or replace function dispatch_broadcast(p_company_id uuid, p_body text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  bid uuid := gen_random_uuid();
  n integer;
begin
  if not is_logistics_member(p_company_id) then
    raise exception 'Not allowed';
  end if;
  if char_length(btrim(coalesce(p_body, ''))) not between 1 and 1000 then
    raise exception 'Write a message of up to 1000 characters';
  end if;
  insert into chat_messages (id, company_id, driver_id, sender_type, sender_user_id, body, broadcast_id)
  select gen_random_uuid(), p_company_id, d.id, 'dispatcher', auth.uid(), btrim(p_body), bid
  from drivers d
  where d.company_id = p_company_id and d.active;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- The company's live topic, for the dashboard to listen on.
create or replace function dispatch_chat_topic(p_company_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select 'co-' || chat_topic from companies
  where id = p_company_id and is_logistics_member(p_company_id);
$$;

grant execute on function dispatch_chat_mark_read(uuid) to authenticated;
grant execute on function dispatch_broadcast(uuid, text) to authenticated;
grant execute on function dispatch_chat_topic(uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- Driver functions (driver link secret, like the other driver_* functions)
-- ---------------------------------------------------------------------------

create or replace function driver_chat_fetch(p_token text, p_since timestamptz default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  me record;
begin
  select * into me from driver_from_token(p_token);
  if not found then
    return null;
  end if;

  return jsonb_build_object(
    'topic', (select 'drv-' || chat_topic from drivers where id = me.driver_id),
    'messages', coalesce((
      select jsonb_agg(m order by m.created_at)
      from (
        select cm.id, cm.order_id, o.reference as order_reference, cm.sender_type, cm.body,
               cm.quick_reply, cm.broadcast_id is not null as is_broadcast, cm.created_at,
               cm.read_by_driver_at, cm.read_by_dispatch_at
        from chat_messages cm
        left join orders o on o.id = cm.order_id
        where cm.driver_id = me.driver_id
          and (p_since is null or cm.created_at > p_since
               or cm.read_by_dispatch_at > p_since or cm.read_by_driver_at > p_since)
        order by cm.created_at desc
        limit 200
      ) m
    ), '[]'::jsonb)
  );
end;
$$;

-- Send a message as the driver. Safe to resend with the same id (offline).
create or replace function driver_chat_send(
  p_token text,
  p_id uuid,
  p_body text,
  p_order_id uuid default null,
  p_quick_reply text default null,
  p_client_sent_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  me record;
begin
  select * into me from driver_from_token(p_token);
  if not found then
    raise exception 'Driver link is not valid' using errcode = '28000';
  end if;

  if exists (select 1 from chat_messages where id = p_id) then
    if exists (select 1 from chat_messages where id = p_id and driver_id = me.driver_id) then
      return jsonb_build_object('ok', true, 'duplicate', true);
    end if;
    raise exception 'Message id already used';
  end if;

  if p_order_id is not null and not exists (
    select 1 from orders where id = p_order_id and driver_id = me.driver_id and company_id = me.company_id
  ) then
    raise exception 'That stop is not assigned to you';
  end if;

  insert into chat_messages (id, company_id, driver_id, order_id, sender_type, body, quick_reply, client_sent_at)
  values (p_id, me.company_id, me.driver_id, p_order_id, 'driver', btrim(p_body),
          nullif(left(p_quick_reply, 40), ''), p_client_sent_at);

  return jsonb_build_object('ok', true);
end;
$$;

create or replace function driver_chat_mark_read(p_token text)
returns integer
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  me record;
  n integer;
begin
  select * into me from driver_from_token(p_token);
  if not found then
    return 0;
  end if;
  update chat_messages
  set read_by_driver_at = now()
  where driver_id = me.driver_id and sender_type = 'dispatcher' and read_by_driver_at is null;
  get diagnostics n = row_count;
  return n;
end;
$$;

revoke all on function driver_chat_fetch(text, timestamptz) from public;
revoke all on function driver_chat_send(text, uuid, text, uuid, text, timestamptz) from public;
revoke all on function driver_chat_mark_read(text) from public;
grant execute on function driver_chat_fetch(text, timestamptz) to anon, authenticated;
grant execute on function driver_chat_send(text, uuid, text, uuid, text, timestamptz) to anon, authenticated;
grant execute on function driver_chat_mark_read(text) to anon, authenticated;

